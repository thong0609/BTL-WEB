    AWAITING_CONFIRMATION = "AWAITING_CONFIRMATION"
    PREPARING = "PREPARING"
    SHIPPING = "SHIPPING"
    COMPLETED = "COMPLETED"
    CANCELLING = "CANCELLING"
    CANCELLED = "CANCELLED"
    REJECTED = "REJECTED"


